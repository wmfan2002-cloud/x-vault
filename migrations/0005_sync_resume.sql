-- 0005: 同步断点续跑
--
-- 修的 bug：第一次同步撞到单轮上限（120）就停了，再点一次却立刻报
-- 「连续 3 位已在你的收录中」然后结束 —— 永远过不了第 120 位。
--
-- 原因：两个调用方都从第 1 位重新扫。前 120 位全是已知的，
-- 「连续 3 个已知即停」的智能增量启发式马上触发。
--
-- 那个启发式本身是对的：正常情况下你已经同步完，又新关注了几个人，
-- X 按关注时间倒序返回，新的在最前面，扫过它们就撞到已知的 -> 该停。
-- 但**在单轮上限截断之后它是错的** —— 此时前面那一段已知恰恰是要跳过的部分。
--
-- 修法：把游标存下来（cursor 列本来就有，只是从没写过），下一轮从游标继续；
-- 且**只要 cursor 非空就关掉「连续已知即停」** —— cursor 非空本身就等于
-- 「还在补历史，不是在找新增」，不需要额外的标志位。
--
-- pass_scanned：一整轮补历史累计扫了多少位，跨多次调用累加，用于前端显示进度。
-- 一轮走完（exhausted）时清零。

ALTER TABLE sync_state      ADD COLUMN pass_scanned INTEGER NOT NULL DEFAULT 0;
ALTER TABLE user_sync_state ADD COLUMN pass_scanned INTEGER NOT NULL DEFAULT 0;
